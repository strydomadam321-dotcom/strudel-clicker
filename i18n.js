const fragments = Object.keys(de)
  .filter((k) => k.length > 2)
  .sort((a, b) => b.length - a.length);
const fragmentPattern = new RegExp(
  fragments.map((k) => k.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|"),
  "g",
);
export function getLanguage() {
  return language;
}
export function bakeryName(name, lang = language) {
  return lang === "de"
    ? `${name}${/[sßxz]$/i.test(name) ? "’" : "s"} Bäckerei`
    : `${name}’s bakery`;
}
export function t(value) {
  const text = String(value);
  if (language !== "de") return text;
  const trim = text.trim(),
    normalized = trim.replace(/\s+/g, " ");
  if (de[normalized]) return text.replace(trim, de[normalized]);
  let result = text;
  const patterns = [
    [
      /^(.+) produce twice as many strudels\.$/,
      (_, name) => `${t(name)} produzieren doppelt so viele Strudel.`,
    ],
    [
      /^Ascend for (.+) Vienna Points?$/,
      (_, n) => `Für ${n} Wien-Punkte aufsteigen`,
    ],
    [
      /^Your next point arrives at (.+) lifetime strudels\.$/,
      (_, n) =>
        `Dein nächster Punkt wird bei insgesamt ${n} Strudeln erreicht.`,
    ],
    [
      /^Your ovens baked (.+) strudels while you were away \(up to 24 hours\)\.$/,
      (_, n) =>
        `Deine Öfen haben während deiner Abwesenheit ${n} Strudel gebacken (bis zu 24 Stunden).`,
    ],
    [
      /^Bake (.+) strudels in total\.$/,
      (_, n) => `Backe insgesamt ${n.replace(/,/g, ".")} Strudel.`,
    ],
    [/^Click (.+) times\.$/, (_, n) => `Klicke ${n.replace(/,/g, ".")} Mal.`],
    [
      /^Own your first (.+)\.$/,
      (_, name) => `Besitze dein erstes Gebäude: ${t(name)}.`,
    ],
    [
      /^Buy (.+) for (.+) strudels$/,
      (_, name, n) => `${t(name)} für ${n} Strudel kaufen`,
    ],
  ];
  for (const [pattern, replace] of patterns)
    if (pattern.test(text)) return text.replace(pattern, replace);
  // Replace nonoverlapping source phrases; never translate the translated output twice.
  return result.replace(fragmentPattern, (key) => de[key]);
}
const originals = new WeakMap();
function translateNode(node) {
  if (node.nodeType === 3) {
    if (
      node.parentElement?.closest("script,style,textarea,[data-user-content]")
    )
      return;
    const record = originals.get(node);
    const english =
      record && node.nodeValue === record.translated
        ? record.english
        : node.nodeValue;
    const translated = t(english);
    originals.set(node, { english, translated });
    if (node.nodeValue !== translated) node.nodeValue = translated;
  } else if (node.nodeType === 1) {
    if (node.matches("script,style,textarea,[data-user-content]")) return;
    for (const attribute of ["title", "aria-label", "placeholder", "alt"]) {
      if (!node.hasAttribute(attribute)) continue;
      const current = node.getAttributeNode(attribute),
        record = originals.get(current);
      const english =
        record && current.value === record.translated
          ? record.english
          : current.value;
      const translated = t(english);
      originals.set(current, { english, translated });
      if (current.value !== translated) current.value = translated;
    }
    for (const child of node.childNodes) translateNode(child);
  }
}
const observer =
  typeof MutationObserver !== "undefined"
    ? new MutationObserver((records) => {
        observer.disconnect();
        for (const record of records) {
          if (record.type === "childList")
            for (const node of record.addedNodes) translateNode(node);
          else translateNode(record.target);
        }
        observe();
      })
    : null;
function observe() {
  observer?.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["title", "aria-label", "placeholder", "alt"],
  });
}
export function applyTranslations() {
  if (typeof document === "undefined") return;
  observer?.disconnect();
  translateNode(document.body);
  document.documentElement.lang = language;
  observe();
}
export function setLanguage(value) {
  language = value === "de" ? "de" : "en";
  applyTranslations();
}
